-- Survive Chaos Online bootstrap
-- Execute in Supabase SQL Editor after creating the project.
-- This file NEVER contains private credentials.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null default 'Jogador' check (char_length(nickname) between 1 and 20),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.player_saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  save jsonb not null default '{}'::jsonb,
  revision bigint not null default 1 check (revision >= 1),
  updated_at timestamptz not null default now()
);

-- Roles are intentionally isolated from profiles so players cannot promote themselves.
create table if not exists public.admin_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'player' check (role in ('player','moderator','admin','owner')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  target_id uuid references auth.users(id) on delete set null,
  command_id text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.match_history (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  match_id uuid,
  mode text,
  difficulty text,
  biome text,
  score bigint not null default 0,
  kills integer not null default 0,
  bosses integer not null default 0,
  duration_seconds integer not null default 0,
  created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
for each row execute procedure public.set_updated_at();

drop trigger if exists player_saves_set_updated_at on public.player_saves;
create trigger player_saves_set_updated_at before update on public.player_saves
for each row execute procedure public.set_updated_at();

drop trigger if exists admin_roles_set_updated_at on public.admin_roles;
create trigger admin_roles_set_updated_at before update on public.admin_roles
for each row execute procedure public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id,nickname,avatar_url)
  values(
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'full_name', new.raw_user_meta_data ->> 'name', split_part(coalesce(new.email,'Jogador'),'@',1), 'Jogador'),20),
    coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.player_saves enable row level security;
alter table public.admin_roles enable row level security;
alter table public.admin_logs enable row level security;
alter table public.match_history enable row level security;

-- Profiles: each authenticated player can see and edit only their own public profile.
drop policy if exists "profile_read_self" on public.profiles;
create policy "profile_read_self" on public.profiles for select to authenticated
using ((select auth.uid()) = id);

drop policy if exists "profile_update_self" on public.profiles;
create policy "profile_update_self" on public.profiles for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

-- Cloud save: each player controls only their own row.
drop policy if exists "save_read_self" on public.player_saves;
create policy "save_read_self" on public.player_saves for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "save_insert_self" on public.player_saves;
create policy "save_insert_self" on public.player_saves for insert to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "save_update_self" on public.player_saves;
create policy "save_update_self" on public.player_saves for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

-- Match history: player may read/insert their own records. Server can do more via service_role.
drop policy if exists "history_read_self" on public.match_history;
create policy "history_read_self" on public.match_history for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "history_insert_self" on public.match_history;
create policy "history_insert_self" on public.match_history for insert to authenticated
with check ((select auth.uid()) = user_id);

-- Deliberately NO authenticated policies for admin_roles/admin_logs.
-- Only trusted server code using service_role should read/write those tables.

grant usage on schema public to authenticated;
grant select, update on public.profiles to authenticated;
grant select, insert, update on public.player_saves to authenticated;
grant select, insert on public.match_history to authenticated;
grant all on public.profiles, public.player_saves, public.admin_roles, public.admin_logs, public.match_history to service_role;
grant usage, select on all sequences in schema public to service_role;

